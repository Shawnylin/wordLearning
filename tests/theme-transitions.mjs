import assert from 'node:assert/strict'
import { launchBrowser, base } from './helpers/browser.mjs'
const browser = await launchBrowser()
try {
  const page = await browser.newPage({ viewport: { width: 393, height: 852 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(`${base}#/profile`)
  await page.getByText('跟随系统', { exact: true }).last().waitFor()
  await page.locator('button').filter({ has: page.locator('span.absolute') }).click()
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await page.waitForTimeout(400)
  for (const route of ['learn', 'compare', 'record', 'report', 'review', 'profile/models', 'profile']) {
    await page.evaluate(route => { location.hash = `#/${route}` }, route)
    await page.waitForTimeout(550)
    assert.equal(await page.locator('html.dark').count(), 1)
    const colors = await page.evaluate(() => {
      const s = getComputedStyle(document.documentElement)
      return ['--paper','--card','--soft','--line','--ink'].map(k => s.getPropertyValue(k).trim())
    })
    assert.deepEqual(colors, ['#141618','#1d2023','#272b2f','#383e44','#e7eaed'])
    assert(await page.locator('main').innerText())
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  }
  await page.screenshot({ path: 'docs/.local/browser-artifacts/theme-neutral-dark.png', fullPage: true })
  await page.getByRole('button', { name: '清空搜索历史', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).waitFor()
  await page.waitForTimeout(300)
  await page.getByRole('button', { name: '取消', exact: true }).click()
  assert(await page.evaluate(() => document.getAnimations().some(a => a.playState === 'running')))
  await page.getByText('清空搜索历史？', { exact: true }).waitFor({ state: 'detached' })
  await page.evaluate(() => { location.hash = '#/compare' })
  await page.getByPlaceholder('输入词语 1').fill('甲')
  await page.getByPlaceholder('输入词语 2').fill('乙')
  await page.getByRole('button', { name: '添加词语' }).click()
  await page.getByPlaceholder('输入词语 3').fill('丙')
  await page.getByTitle('移除').nth(1).click()
  await page.waitForTimeout(350)
  assert.equal(await page.getByPlaceholder('输入词语 2').inputValue(), '丙')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: '添加词语' }).click()
  await page.waitForTimeout(80)
  assert.equal(await page.evaluate(() => document.getAnimations().filter(a => a.playState === 'running').length), 0)
  await page.reload()
  assert.equal(await page.locator('html.dark').count(), 1)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ passed: true, routes: 7, darkThemePersisted: true, reducedMotion: true, errors }))
} finally { await browser.close() }
